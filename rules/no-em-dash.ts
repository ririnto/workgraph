import type { MicromarkToken, Rule, RuleParams } from "markdownlint";

type SourceRange = readonly [start: number, end: number];

const licenseNamePattern =
  /(?:^|[/\\])(?:licen[cs]e|copying)(?:[.-][^/\\]*)?$/iu;
const generatedMarkerPattern =
  /^\s*(?:<!--\s*(?:(?:code\s+|automatically\s+|auto-?|@)?generated)\b|(?:generated|autogenerated):\s*true\s*$)/iu;
const quoteAfterLinkPattern =
  /^(?<separator>:[ \t]*)(?<quote>"(?:\\[\s\S]|[^"\\\r\n])*"|“(?:\\[\s\S]|[^”\\\r\n])*”|'(?:\\[\s\S]|(?<=\w)'(?=\w)|[^'\\\r\n])*'(?!\w)|‘(?:\\[\s\S]|(?<=\w)’(?=\w)|[^’\\\r\n])*’)/u;

/**
 * Identify generated documents and license files whose original content is preserved.
 *
 * @param params Markdownlint input for one document.
 * @returns Whether the document has a recognized generated marker or license filename.
 */
export const protectedDocument = (params: RuleParams): boolean =>
  licenseNamePattern.test(params.name) ||
  params.frontMatterLines.some((line) => generatedMarkerPattern.test(line)) ||
  (params.parsers.micromark?.tokens ?? []).some(
    (token) =>
      token.type === "htmlFlow" &&
      token.startLine <= 5 &&
      generatedMarkerPattern.test(token.text)
  );

/**
 * Find quotations after a parsed inline source link on the same line.
 *
 * @param params Markdownlint source lines and parsed tokens.
 * @returns Quotation ranges keyed by their 1-based source line.
 */
export const sourceAttributedQuoteRanges = (
  params: RuleParams
): Map<number, SourceRange[]> => {
  const ranges = new Map<number, SourceRange[]>();
  const pending = [...(params.parsers.micromark?.tokens ?? [])];
  for (let token = pending.pop(); token !== undefined; token = pending.pop()) {
    if (
      token.type === "link" &&
      token.startLine === token.endLine &&
      token.children.some(
        ({ children, type }) =>
          type === "resource" &&
          children.some(
            ({ text, type: childType }) =>
              childType === "resourceDestination" && text !== "<>"
          )
      )
    ) {
      const linkEnd = token.endColumn - 1;
      const suffix = params.lines[token.startLine - 1]?.slice(linkEnd) ?? "";
      const { quote, separator } =
        quoteAfterLinkPattern.exec(suffix)?.groups ?? {};
      if (quote !== undefined && separator !== undefined) {
        const start = linkEnd + separator.length;
        const lineRanges = ranges.get(token.startLine) ?? [];
        lineRanges.push([start, start + quote.length]);
        ranges.set(token.startLine, lineRanges);
      }
    }
    pending.push(...token.children);
  }
  return ranges;
};

const rule: Rule = {
  description: "Prose and headings must not contain em dashes",
  function: (params, onError) => {
    if (protectedDocument(params)) {
      return;
    }
    const attributedQuotes = sourceAttributedQuoteRanges(params);
    const pending: MicromarkToken[] = [
      ...(params.parsers.micromark?.tokens ?? [])
    ];
    for (
      let token = pending.pop();
      token !== undefined;
      token = pending.pop()
    ) {
      if (token.type === "data") {
        let { parent } = token;
        let prose = false;
        let excluded = false;
        while (parent) {
          if (
            [
              "codeText",
              "literalAutolink",
              "autolink",
              "resource",
              "definition",
              "labelText"
            ].includes(parent.type)
          ) {
            excluded = true;
          }
          if (
            [
              "paragraph",
              "atxHeadingText",
              "setextHeadingText",
              "tableData",
              "tableHeader"
            ].includes(parent.type)
          ) {
            prose = true;
          }
          ({ parent } = parent);
        }
        if (prose && !excluded) {
          for (const [index, line] of token.text
            .split(/\r\n|[\r\n]/u)
            .entries()) {
            for (const match of line.matchAll(/\u2014/gu)) {
              const lineNumber = token.startLine + index;
              const sourceColumn =
                (index === 0 ? token.startColumn : 1) + (match.index ?? 0);
              if (
                !(attributedQuotes.get(lineNumber) ?? []).some(
                  ([start, end]) =>
                    start <= sourceColumn - 1 && sourceColumn - 1 < end
                )
              ) {
                onError({
                  lineNumber,
                  range: [sourceColumn, 1]
                });
              }
            }
          }
        }
      } else {
        pending.push(...token.children);
      }
    }
  },
  names: ["docs/no-em-dash"],
  parser: "micromark",
  tags: ["docs"]
};

/**
 * Provide the prose em-dash Markdownlint rule.
 */
export default rule;
